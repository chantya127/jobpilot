"""Per-worker browser windows. Each worker = its own Chromium-family browser profile on its own CDP port, driven by
agent-browser through a generated wrapper script ($JP_HOME/bin/abN)."""
import os
import platform
import shutil
import socket
import stat
import subprocess
import time
from pathlib import Path

from . import config
from .procs import exe as _exe, group_kwargs, posix

BASE_PORT = 9333


def _win_candidates() -> list[str]:
    bases = [os.environ.get(v) for v in ("PROGRAMFILES", "PROGRAMFILES(X86)", "LOCALAPPDATA")]
    rels = [r"Google\Chrome\Application\chrome.exe", r"BraveSoftware\Brave-Browser\Application\brave.exe",
            r"Chromium\Application\chrome.exe", r"Microsoft\Edge\Application\msedge.exe"]
    return [os.path.join(b, r) for r in rels for b in bases if b]


CANDIDATES = {
    "Darwin": [
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
        "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser",
        "/Applications/Chromium.app/Contents/MacOS/Chromium",
        "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
    ],
    "Linux": ["google-chrome", "google-chrome-stable", "brave-browser", "chromium", "chromium-browser", "microsoft-edge",
              "microsoft-edge-stable"],
    "Windows": _win_candidates(),
}

# Where each browser keeps its normal user profiles (for the opt-in "copy my profile" option).
USER_DATA = {
    "Darwin": {
        "Chrome": "~/Library/Application Support/Google/Chrome",
        "Brave": "~/Library/Application Support/BraveSoftware/Brave-Browser",
        "Edge": "~/Library/Application Support/Microsoft Edge",
    },
    "Linux": {
        "Chrome": "~/.config/google-chrome",
        "Brave": "~/.config/BraveSoftware/Brave-Browser",
        "Edge": "~/.config/microsoft-edge",
    },
    "Windows": {
        "Chrome": "~/AppData/Local/Google/Chrome/User Data",
        "Brave": "~/AppData/Local/BraveSoftware/Brave-Browser/User Data",
        "Edge": "~/AppData/Local/Microsoft/Edge/User Data",
    },
}


def detect() -> list[str]:
    found = []
    for c in CANDIDATES.get(platform.system(), []):
        p = c if os.path.isabs(c) else shutil.which(c)
        if p and os.path.exists(p):
            found.append(p)
    return found


def browser_path() -> str:
    s = config.load_settings()
    if s.get("browser_path") and os.path.exists(s["browser_path"]):
        return s["browser_path"]
    found = detect()
    return found[0] if found else ""


def port(worker: int) -> int:
    return BASE_PORT + worker - 1


def profile_dir(worker: int) -> Path:
    return config.PROFILES / f"w{worker}"


def is_up(worker: int) -> bool:
    try:
        with socket.create_connection(("127.0.0.1", port(worker)), timeout=0.5):
            return True
    except OSError:
        return False


def ab_cmd(worker: int) -> list[str]:
    """agent-browser bound to this worker's browser, for calls from Python (the bin/abN wrappers are bash scripts,
    which Windows can't exec directly; agents use the wrappers from their Bash tool)."""
    return [_exe("agent-browser"), "--session", f"jobpilot-w{worker}", "--cdp", str(port(worker))]


def browser_args(worker: int, url: str = "about:blank") -> list[str]:
    return [f"--user-data-dir={profile_dir(worker)}", f"--remote-debugging-port={port(worker)}",
            "--no-first-run", "--no-default-browser-check", "--disable-blink-features=AutomationControlled",
            "--window-size=1440,900", url]


def write_wrappers(n: int) -> None:
    """bin/ab1..abN: start that worker's browser if needed, then exec agent-browser against its CDP port.
    Bash scripts with LF line endings and POSIX paths, so they run in macOS/Linux bash and in Git Bash on Windows."""
    config.ensure_dirs()
    exe = posix(browser_path())
    for w in range(1, n + 1):
        profile_dir(w).mkdir(parents=True, exist_ok=True)
        script = f"""#!/usr/bin/env bash
# Generated by JobPilot: browser for worker {w}. Edit the browser in the dashboard Settings, not here.
P={port(w)}
if ! curl -s -m 2 "http://127.0.0.1:$P/json/version" >/dev/null; then
  ("{exe}" --user-data-dir="{posix(profile_dir(w))}" --remote-debugging-port=$P \\
    --no-first-run --no-default-browser-check --disable-blink-features=AutomationControlled \\
    --window-size=1440,900 about:blank >/dev/null 2>&1 &)
  for i in $(seq 1 30); do curl -s -m 1 "http://127.0.0.1:$P/json/version" >/dev/null && break; sleep 0.5; done
fi
AB=(agent-browser --session jobpilot-w{w} --cdp $P)
# Review mode (auto-submit OFF): re-arm the review lock around every action that could submit a form.
if [ "$JP_REVIEW" = 1 ] && [ -f "$JP_ENGINE/review_guard.js" ]; then
  case "$1" in
    open|tab|click|dblclick|fill|type|press|keyboard|select|check|reload|upload|find)
      G=$(cat "$JP_ENGINE/review_guard.js")
      "${{AB[@]}}" eval "$G" >/dev/null 2>&1
      "${{AB[@]}}" "$@"; rc=$?
      "${{AB[@]}}" eval "$G" >/dev/null 2>&1
      exit $rc ;;
  esac
fi
exec "${{AB[@]}}" "$@"
"""
        f = config.BIN / f"ab{w}"
        f.write_text(script, encoding="utf-8", newline="\n")
        f.chmod(f.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def launch(worker: int, url: str = "about:blank") -> None:
    """Open the worker's browser window (used for 'log in to LinkedIn/Gmail once' and to show a waiting tab)."""
    exe = browser_path()
    if not exe:
        raise RuntimeError("No Chromium-based browser found. Install Chrome/Brave/Chromium or set its path in Settings.")
    profile_dir(worker).mkdir(parents=True, exist_ok=True)
    if is_up(worker):
        subprocess.Popen([*ab_cmd(worker), "tab", "new", url], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                         **group_kwargs())
        return
    # Own session/process group: the window survives the dashboard and the agents that use it.
    subprocess.Popen([exe, *browser_args(worker, url)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                     **group_kwargs(gui=True))
    for _ in range(30):
        if is_up(worker):
            return
        time.sleep(0.3)


def ensure_up(worker: int) -> None:
    """Start the worker's browser from here (detached) before an agent uses it, so stopping the agent's process
    tree never closes the window and the forms waiting for review in it."""
    if not is_up(worker) and browser_path():
        launch(worker)


def show_url(worker: int, url: str) -> str:
    """Bring up `url` in this worker's own browser window: focus the tab that already has that job open (the filled
    form waiting for you), else open it in a new tab there. Returns 'focused' | 'opened'."""
    import json as _json
    import urllib.parse as _up
    import urllib.request as _ur
    from .db import ukey
    if not is_up(worker):
        launch(worker, url)
        return "opened"
    base = f"http://127.0.0.1:{port(worker)}"
    try:
        tabs = [t for t in _json.load(_ur.urlopen(f"{base}/json/list", timeout=3)) if t.get("type") == "page"]
    except Exception:
        tabs = []
    want, host = ukey(url), _up.urlsplit(url).netloc.lower()
    hit = next((t for t in tabs if ukey(t.get("url", "")) == want), None) \
        or next((t for t in reversed(tabs) if _up.urlsplit(t.get("url", "")).netloc.lower() == host), None)
    if hit:
        _ur.urlopen(f"{base}/json/activate/{hit['id']}", timeout=3)
        return "focused"
    try:
        _ur.urlopen(_ur.Request(f"{base}/json/new?{_up.quote(url, safe=':/?&=%#')}", method="PUT"), timeout=5)
    except Exception:
        subprocess.Popen([*ab_cmd(worker), "tab", "new", url], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                         **group_kwargs())
    return "opened"


def existing_profiles() -> list[dict]:
    """Normal browser profiles on this machine that can be copied into worker profiles."""
    out = []
    for name, base in USER_DATA.get(platform.system(), {}).items():
        b = Path(base).expanduser()
        if not b.exists():
            continue
        for d in sorted(b.iterdir()):
            if d.is_dir() and (d.name == "Default" or d.name.startswith("Profile ")) and (d / "Preferences").exists():
                out.append({"browser": name, "path": str(d), "label": f"{name} – {d.name}"})
    return out


def copy_profile(src: str, workers: int) -> None:
    """Copy one real browser profile into every worker (as their 'Default'). The browser must be closed first.
    Logins only carry over when the worker uses the same browser (it shares that browser's keychain entry)."""
    s = Path(src)
    base = s.parent
    skip = shutil.ignore_patterns("Cache", "Code Cache", "GPUCache", "Service Worker", "*.lock", "Singleton*")
    for w in range(1, workers + 1):
        dst = profile_dir(w)
        if dst.exists():
            shutil.rmtree(dst)
        dst.mkdir(parents=True)
        if (base / "Local State").exists():
            shutil.copy2(base / "Local State", dst / "Local State")
        shutil.copytree(s, dst / "Default", ignore=skip, symlinks=True)
