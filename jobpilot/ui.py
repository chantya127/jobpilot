STATUS_LABELS = {
    "queued": "Queued", "running": "Running", "applied": "Applied", "ready-for-review": "Ready for review",
    "pending-user": "Needs you", "blocked": "Blocked", "skipped": "Skipped", "easy-apply": "Easy Apply",
    "failed": "Failed", "stopped": "Stopped",
}


def icon_svg(name: str, size: int = 16) -> str:
    return (f'<svg class="i" width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
            f'stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{ICONS[name]}</svg>')


def icon(name: str, size: int = 16) -> Markup:
    return Markup(icon_svg(name, size))


def status_label(s) -> str:
    return STATUS_LABELS.get(s or "", (s or "").replace("-", " ").capitalize())


def register(env) -> None:
    env.globals.update(icon=icon, ICONS={k: icon_svg(k) for k in ICONS}, STATUS_LABELS=STATUS_LABELS)
    env.filters["status_label"] = status_label
